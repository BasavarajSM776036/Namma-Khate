let currentLang = 'en';

export function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('mk_lang', lang);
  document.documentElement.setAttribute('lang', lang === 'kn' ? 'kn' : 'en');
}

export function getLanguage() {
  return currentLang;
}

export function loadLanguage() {
  currentLang = localStorage.getItem('mk_lang') || 'en';
  document.documentElement.setAttribute('lang', currentLang === 'kn' ? 'kn' : 'en');
  return currentLang;
}

export function t(key) {
  const entry = TRANSLATIONS[key];
  if (!entry) return key;
  return entry[currentLang] || entry['en'] || key;
}

export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
}

export const MONTH_NAMES = [
  'january','february','march','april','may','june',
  'july','august','september','october','november','december'
];

export const DAY_NAMES = [
  'monday','tuesday','wednesday','thursday','friday','saturday','sunday'
];

export function formatDate(dateStr) {
  // dateStr is YYYY-MM-DD, returns DD/MM/YYYY
  if (!dateStr) return '';
  const [y, m, d] = dateStr.split('-');
  return `${d}/${m}/${y}`;
}

export function formatCurrency(amount) {
  const num = parseFloat(amount) || 0;
  return '₹' + num.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

export function formatCurrencyShort(amount) {
  const num = parseFloat(amount) || 0;
  if (num >= 100000) return '₹' + (num / 100000).toFixed(2) + 'L';
  if (num >= 1000) return '₹' + (num / 1000).toFixed(1) + 'K';
  return '₹' + num.toFixed(2);
}

export function getMonthName(monthIndex) {
  return t(MONTH_NAMES[monthIndex]);
}

export function getDayName(dayIndex) {
  // 0=Monday...6=Sunday
  return t(DAY_NAMES[dayIndex]);
}
